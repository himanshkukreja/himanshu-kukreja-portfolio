// Files the server used to read from disk at runtime, bundled as modules instead (src/generated/og-fonts.ts, stories.ts):
// the OG card fonts, the repo's stories (content/stories/*.md) and each story activity's title/blurb.
// Workers (Cloudflare) have no filesystem, and a bundled module is faster than a read on any host.
// Runs before `next dev` and `next build` (package.json predev/prebuild). Output is ASCII-only (\u escapes).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const ascii = (v) => JSON.stringify(v).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));

// OG fonts (satori needs static TTFs)
const fontDir = join(root, "src/lib/og/fonts");
const fonts = Object.fromEntries(
  ["Bricolage-800", "Bricolage-700", "Geist-400", "Geist-500", "GeistMono-400", "GeistMono-600"].map((n) => [n, readFileSync(join(fontDir, `${n}.ttf`)).toString("base64")])
);

// stories: file name -> raw markdown
const storyDir = join(root, "content/stories");
const stories = readdirSync(storyDir)
  .filter((n) => n.endsWith(".md"))
  .sort()
  .map((name) => ({ name, raw: readFileSync(join(storyDir, name), "utf8") }));

// story activities: slug -> { kind, title, blurb, minutes } (from the activity sources' ActivityDef)
const actDir = join(root, "src/components/stories/activities");
const strLit = (src, key) => {
  const m = new RegExp(`${key}:\\s*\\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(src);
  return m ? m[1].replace(/\\"/g, '"').replace(/\\n/g, " ") : null;
};
const activities = {};
const registry = readFileSync(join(actDir, "registry.tsx"), "utf8");
for (const m of registry.matchAll(/"([a-z0-9-]+)":\s*dynamic\(\(\)\s*=>\s*import\("\.\/([A-Za-z0-9]+)"\)/g)) {
  try {
    const src = readFileSync(join(actDir, `${m[2]}.tsx`), "utf8");
    const def = src.slice(src.indexOf(": ActivityDef = {"));
    const title = strLit(def, "title");
    if (title) activities[m[1]] = { kind: strLit(def, "kind") || "activity", title, blurb: strLit(def, "blurb") || "", minutes: Number(/minutes:\s*(\d+)/.exec(def)?.[1] || 0) };
  } catch {
    /* one unreadable activity doesn't matter */
  }
}

mkdirSync(join(root, "src/generated"), { recursive: true });
const head = "// Generated by scripts/build/gen-runtime-files.mjs (predev/prebuild). Do not edit.\n";
// separate modules, so a route that only needs the stories doesn't carry ~600 KB of fonts
writeFileSync(join(root, "src/generated/og-fonts.ts"), head + `/** OG card fonts, base64 TTF by "Family-weight" */\nexport const OG_FONTS: Record<string, string> = ${ascii(fonts)};\n`);
writeFileSync(
  join(root, "src/generated/stories.ts"),
  head +
    `/** content/stories/*.md */\nexport const STORY_FILES: { name: string; raw: string }[] = ${ascii(stories)};\n` +
    `/** story activity title/blurb by story slug */\nexport const STORY_ACTIVITIES: Record<string, { kind: string; title: string; blurb: string; minutes: number }> = ${ascii(activities)};\n`
);
console.log(`runtime-files: ${Object.keys(fonts).length} fonts, ${stories.length} stories, ${Object.keys(activities).length} activities`);
