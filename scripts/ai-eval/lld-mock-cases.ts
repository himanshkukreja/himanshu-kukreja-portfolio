/**
 * Eval cases for the LLD (machine-coding) mock interviewer ("lld-mock"): scripted candidate turns on three case studies
 * (parking lot, elevator, digital wallet) across all five phases, one per kind of turn the interviewer must handle.
 * The runner (lld-mock.ts) builds each turn exactly as /api/learn/ai/mock/turn does and checks the reply.
 */

export type LldTurnKind =
  | "clarify-good"
  | "clarify-vague"
  | "clarify-unknown"
  | "ask-classes"
  | "ask-solution"
  | "off-topic"
  | "wrong-claim"
  | "long"
  | "silent"
  | "done"
  | "change-due"
  | "change-handled"
  | "on-track";

export type LldEvalCase = {
  id: string;
  /** the case study (resources/low-level-design/<slug>.md) */
  slug: "lld-01-parking-lot" | "lld-04-elevator-system" | "lld-25-digital-wallet";
  phase: "p1" | "p2" | "p3" | "p4" | "p5";
  kind: LldTurnKind;
  title: string;
  /** the attempt's requirement change (its id in mock.lld.changes) and whether the room has announced it */
  change?: { id: string; announced: boolean };
  /** earlier turns of this phase, oldest first, starting with the candidate */
  history?: { role: "user" | "assistant"; content: string }[];
  input: string;
  /** what this reply must do / must not do (on top of the checks every reply gets) */
  expect: string[];
  mustNot?: string[];
  /** a reply of OFF_TOPIC is acceptable (a request for unrelated work, not small talk) */
  offTopicOk?: boolean;
};

