-- Case files CMS (/admin/case-files): write, keep in draft, publish, archive case files from the admin.
-- Additive only: two new tables, one trigger function, one public Storage bucket. Nothing existing is
-- altered or dropped. The repo stories (content/stories/*.md) keep working without this migration.
--
-- Access: RLS on with NO policies and all privileges revoked from anon/authenticated, so only the
-- service role (server code behind requireAdmin, and the public story pages rendering server-side)
-- can read or write. Readers never query these tables directly.

create extension if not exists pgcrypto;

-- ── case files ──────────────────────────────────────────────────────────────────────────────────
-- Working copy = the columns below (what the editor autosaves). `live` = the snapshot the public
-- site reads, copied from the working copy on publish ("Update live"). Editing a published case
-- file never changes the public page until it is published again.
create table if not exists public.case_files (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) between 3 and 80),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),

  -- frontmatter
  title text not null default '',
  excerpt text not null default '',
  type text not null default 'incident' check (type in ('incident', 'design', 'build')),
  tags text[] not null default '{}',
  date date,                              -- the "opened" date shown on the case file
  cover_url text,                         -- 1536×1024 blueprint (Storage public URL or /covers/…)
  cover_alt text,
  motion_cover_url text,                  -- optional transparent animated SVG layered over the cover
  seo_title text,
  seo_description text,

  -- content
  body_md text not null default '',       -- markdown: ## chapters, ```mermaid, ::: blocks, images
  debrief jsonb,                          -- { question, options[], answer, explain }
  activity jsonb,                         -- data-driven end-of-file activity (components/stories/activities/data.ts)

  -- publishing
  overrides_file boolean not null default false,  -- imported from content/stories/<slug>.md: replaces it while published
  case_number integer unique,             -- CASE-0NN, assigned at first publish, never reused
  live jsonb,                             -- published snapshot (null unless status = 'published')
  live_version integer,                   -- working version the live snapshot was taken from
  published_at timestamptz,               -- first publish
  last_published_at timestamptz,
  archived_at timestamptz,

  -- bookkeeping
  version integer not null default 1,     -- bumps on every save (optimistic locking for the editor)
  validation jsonb,                       -- last validator summary { ok, errors, warnings, problems[], stats }
  created_by text,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint case_files_live_when_published check (status <> 'published' or live is not null)
);
create index if not exists case_files_status_idx on public.case_files (status);
create index if not exists case_files_updated_idx on public.case_files (updated_at desc);

-- ── revisions: one snapshot per save / publish / unpublish / archive / restore ─────────────────
-- Autosaves within ~10 minutes of each other refresh one "autosave" row instead of adding rows.
create table if not exists public.case_file_revisions (
  id bigint generated by default as identity primary key,
  case_file_id uuid not null references public.case_files (id) on delete cascade,
  version integer not null,
  action text not null check (action in ('create', 'save', 'autosave', 'publish', 'unpublish', 'archive', 'restore', 'import', 'revert', 'duplicate')),
  snapshot jsonb not null,                -- the working copy's fields at that moment
  created_by text,
  created_at timestamptz not null default now()
);
create index if not exists case_file_revisions_file_idx on public.case_file_revisions (case_file_id, created_at desc);

-- keep updated_at honest even for writes that forget it
create or replace function public.case_files_touch() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists case_files_touch on public.case_files;
create trigger case_files_touch before update on public.case_files
  for each row execute function public.case_files_touch();

-- ── lock it down: service role only ─────────────────────────────────────────────────────────────
alter table public.case_files enable row level security;
alter table public.case_file_revisions enable row level security;
revoke all on public.case_files from anon, authenticated;
revoke all on public.case_file_revisions from anon, authenticated;
grant all on public.case_files to service_role;
grant all on public.case_file_revisions to service_role;
grant usage, select on all sequences in schema public to service_role;

-- ── Storage: covers + inline images (public read) ──────────────────────────────────────────────
-- Public bucket: objects are readable at /storage/v1/object/public/case-files/<slug>/<file> with no
-- policy. Nobody but the service role can write: the admin API hands the browser a one-time signed
-- upload URL for one path after checking the type and size, and the bucket enforces both again.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'case-files',
  'case-files',
  true,
  6291456,                                -- 6 MB (motion SVGs are capped at 1 MB by the API)
  array['image/png', 'image/jpeg', 'image/webp', 'image/avif', 'image/gif', 'image/svg+xml']
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
