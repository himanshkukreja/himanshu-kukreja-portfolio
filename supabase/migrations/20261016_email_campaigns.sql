-- Email campaigns for /admin/newsletter (compose → audience → preview/test → batched send → tracking).
-- Additive only: five new tables + one function. Nothing existing is altered or dropped.
-- Access: RLS on with NO policies, and all privileges revoked from anon/authenticated, so only the
-- service role (server code) can read or write. The public tracking routes run server-side too.

create extension if not exists pgcrypto;

-- ── sender identities ("from" addresses on a transport) ─────────────────────────────────────────
-- The env defaults (SMTP_FROM, SMTP2_FROM) are not stored here; the app always lists them.
create table if not exists public.email_senders (
  id uuid primary key default gen_random_uuid(),
  label text not null,
  from_name text not null default '',
  from_email text not null,
  reply_to text,
  transport text not null default 'smtp' check (transport in ('smtp', 'smtp2')),
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists email_senders_single_default on public.email_senders ((is_default)) where is_default;

-- ── campaigns ───────────────────────────────────────────────────────────────────────────────────
create table if not exists public.email_campaigns (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  subject text not null,
  subject_fallback text,                 -- used when a tag in the subject has no value
  preheader text,
  template text not null default 'blank',
  doc jsonb not null,                    -- { layout: "blocks" | "raw", ... }
  sender_id text,                        -- 'env:smtp' | 'env:smtp2' | email_senders.id
  sender jsonb,                          -- snapshot {fromName, fromEmail, replyTo, transport} at queue time
  audience jsonb not null default '{"kind":"learners"}'::jsonb,
  track_opens boolean not null default true,
  track_clicks boolean not null default true,
  status text not null default 'draft' check (status in ('draft', 'sending', 'paused', 'sent', 'cancelled')),
  last_error text,
  lock_until timestamptz,                -- per-campaign send lease (one batch runner at a time)
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  queued_at timestamptz,
  started_at timestamptz,
  finished_at timestamptz
);
create index if not exists email_campaigns_created_idx on public.email_campaigns (created_at desc);
create index if not exists email_campaigns_status_idx on public.email_campaigns (status);

-- ── one row per recipient per campaign ──────────────────────────────────────────────────────────
create table if not exists public.email_messages (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.email_campaigns (id) on delete cascade,
  email text not null,
  user_id uuid,
  name text,
  token text not null,                   -- random, per recipient: pixel / click / unsubscribe links
  status text not null default 'queued' check (status in ('queued', 'sending', 'sent', 'failed', 'skipped')),
  error text,
  provider_id text,                      -- SMTP message id
  vars jsonb,                            -- merge data actually used
  claimed_at timestamptz,
  sent_at timestamptz,
  open_count integer not null default 0,
  first_open_at timestamptz,
  last_open_at timestamptz,
  click_count integer not null default 0,
  first_click_at timestamptz,
  last_click_at timestamptz,
  unsubscribed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint email_messages_campaign_email_key unique (campaign_id, email)
);
create unique index if not exists email_messages_token_idx on public.email_messages (token);
create index if not exists email_messages_campaign_status_idx on public.email_messages (campaign_id, status, id);

-- ── opens / clicks / unsubscribes ───────────────────────────────────────────────────────────────
create table if not exists public.email_events (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.email_messages (id) on delete cascade,
  campaign_id uuid not null references public.email_campaigns (id) on delete cascade,
  type text not null check (type in ('open', 'click', 'unsubscribe')),
  url text,
  user_agent text,
  created_at timestamptz not null default now()
);
create index if not exists email_events_campaign_idx on public.email_events (campaign_id, created_at desc);
create index if not exists email_events_message_idx on public.email_events (message_id);

-- ── never email again (hard bounces, complaints, manual) ────────────────────────────────────────
create table if not exists public.email_suppressions (
  email text primary key,
  reason text not null check (reason in ('bounce', 'complaint', 'manual')),
  detail text,
  created_at timestamptz not null default now()
);

-- ── atomic open / click counter (called by /api/email/o and /api/email/c) ──────────────────────
-- A click also sets first_open_at (the reader opened it even if images were blocked).
-- Event rows are capped at 50 opens per message so pixel prefetchers can't bloat the table.
create or replace function public.email_track(p_token text, p_type text, p_url text default null, p_ua text default null)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  m_id bigint;
  m_campaign uuid;
  m_opens integer;
begin
  if p_type not in ('open', 'click') then
    return false;
  end if;
  if p_type = 'open' then
    update email_messages
       set open_count = open_count + 1,
           first_open_at = coalesce(first_open_at, now()),
           last_open_at = now()
     where token = p_token
     returning id, campaign_id, open_count into m_id, m_campaign, m_opens;
  else
    update email_messages
       set click_count = click_count + 1,
           first_click_at = coalesce(first_click_at, now()),
           last_click_at = now(),
           first_open_at = coalesce(first_open_at, now())
     where token = p_token
     returning id, campaign_id, open_count into m_id, m_campaign, m_opens;
  end if;
  if m_id is null then
    return false;
  end if;
  if p_type = 'click' or m_opens <= 50 then
    insert into email_events (message_id, campaign_id, type, url, user_agent)
    values (m_id, m_campaign, p_type, left(p_url, 1000), left(p_ua, 300));
  end if;
  return true;
end;
$$;

-- ── lock it down: service role only ─────────────────────────────────────────────────────────────
alter table public.email_senders enable row level security;
alter table public.email_campaigns enable row level security;
alter table public.email_messages enable row level security;
alter table public.email_events enable row level security;
alter table public.email_suppressions enable row level security;

revoke all on public.email_senders, public.email_campaigns, public.email_messages, public.email_events, public.email_suppressions from anon, authenticated;
revoke all on function public.email_track(text, text, text, text) from public, anon, authenticated;
grant execute on function public.email_track(text, text, text, text) to service_role;
grant all on public.email_senders, public.email_campaigns, public.email_messages, public.email_events, public.email_suppressions to service_role;
grant usage, select on all sequences in schema public to service_role;

-- refresh PostgREST so the API sees the new tables right away
notify pgrst, 'reload schema';
